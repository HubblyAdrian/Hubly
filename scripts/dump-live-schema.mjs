/**
 * What is ACTUALLY in the database, as far as PostgREST will tell us.
 *
 * WHY THIS EXISTS
 *
 * The repo is not the source of truth for this database. On 2026-08-19 a
 * migration was built by copying a function body out of supabase/migrations/ --
 * because the repo was all that could be read -- and the copy was two revisions
 * behind what was live. It silently reverted a validation block and introduced
 * two type mismatches, and took down every draft write on production.
 *
 * The specific facts that would have prevented it are all here: service_area_cities
 * is jsonb, section_order is text[], and there is no postal_code column at all.
 *
 * WHAT THIS IS NOT
 *
 * NOT a pg_dump. PostgREST exposes tables, columns, types and callable RPC
 * signatures -- it does not expose FUNCTION BODIES or RLS POLICIES, which is
 * precisely the half that caused the incident. A real `supabase db dump`
 * (Docker, or pg_dump with the database password) is still owed. Treat this as
 * the column-and-signature half of the answer, and say so when citing it.
 *
 * Usage:
 *   SUPABASE_SERVICE_ROLE_KEY=… node scripts/dump-live-schema.mjs
 */
import { writeFileSync } from 'node:fs';

const URL_ = process.env.SUPABASE_URL || 'https://rtwxxkxpkqdrhclkozma.supabase.co';
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SRK;
if (!KEY) { console.error('SUPABASE_SERVICE_ROLE_KEY must be set.'); process.exit(1); }

const res = await fetch(`${URL_}/rest/v1/`, { headers: { apikey: KEY, authorization: `Bearer ${KEY}` } });
if (!res.ok) { console.error('introspection failed:', res.status); process.exit(1); }
const spec = await res.json();

const defs = spec.definitions || {};
const paths = spec.paths || {};

const lines = [];
lines.push('# Live schema — columns and RPC signatures');
lines.push('');
lines.push('GENERATED by `scripts/dump-live-schema.mjs`. Do not hand-edit.');
lines.push('');
lines.push('**This is not a `pg_dump`.** PostgREST exposes tables, columns, types and');
lines.push('callable RPC signatures. It does NOT expose function bodies or RLS policies —');
lines.push('which is exactly the half that caused the 2026-08-19 incident, where a function');
lines.push('body was rebuilt from a repo copy two revisions behind the database. A real');
lines.push('`supabase db dump --schema public` is still owed and needs Docker or the');
lines.push('database password.');
lines.push('');
lines.push('Check this file before writing any migration that references a column.');
lines.push('');

const tables = Object.keys(defs).sort();
lines.push(`## Tables and views (${tables.length})`);
lines.push('');
for (const t of tables) {
  const props = defs[t].properties || {};
  const required = new Set(defs[t].required || []);
  const cols = Object.keys(props);
  lines.push(`### ${t}  (${cols.length} columns)`);
  lines.push('');
  lines.push('```');
  for (const c of cols) {
    const p = props[c] || {};
    const type = p.format || p.type || '?';
    const pk = /primary key/i.test(p.description || '') ? ' PK' : '';
    const fk = /<fk table=/.test(p.description || '')
      ? ' -> ' + (/<fk table='([^']+)' column='([^']+)'/.exec(p.description) || [, '?', '?']).slice(1, 3).join('.')
      : '';
    lines.push(`${c.padEnd(34)} ${type}${required.has(c) ? ' NOT NULL' : ''}${pk}${fk}`);
  }
  lines.push('```');
  lines.push('');
}

const rpcs = Object.keys(paths).filter((p) => p.startsWith('/rpc/')).sort();
lines.push(`## Callable RPCs (${rpcs.length})`);
lines.push('');
lines.push('Signatures only — PostgREST does not expose bodies. To read a body, find the');
lines.push('LATEST definition in the repo and remember it may still be behind the database:');
lines.push('');
lines.push('```');
lines.push('grep -rln "create or replace function <name>" supabase/migrations/ | sort | tail -1');
lines.push('```');
lines.push('');
lines.push('```');
for (const r of rpcs) {
  const post = paths[r].post || {};
  const params = (post.parameters || [])
    .flatMap((p) => (p.schema && p.schema.properties ? Object.entries(p.schema.properties) : []))
    .map(([k, v]) => `${k} ${v.format || v.type || '?'}`);
  lines.push(`${r.replace('/rpc/', '').padEnd(40)} (${params.join(', ')})`);
}
lines.push('```');
lines.push('');

writeFileSync('docs/live-schema.md', lines.join('\n') + '\n');
console.log(`wrote docs/live-schema.md — ${tables.length} tables, ${rpcs.length} rpcs, ${lines.length} lines`);
